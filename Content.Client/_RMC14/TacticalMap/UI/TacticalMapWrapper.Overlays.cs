    private void ToggleRadiusOverlay(RadiusOverlayMode mode)
    {
        _radiusOverlayMode = _radiusOverlayMode == mode ? RadiusOverlayMode.None : mode;
        ApplyRadiusOverlay();
        UpdateRadiusOverlayButtons();
    }

    private void ApplyRadiusOverlay()
    {
        switch (_radiusOverlayMode)
        {
            case RadiusOverlayMode.OrbitalBombardment:
                SetRadiusPreview(_orbitalRadiusTiles, OrbitalRadiusColor, TacticalMapControl.RadiusPreviewFilterMode.OrbitalBombardment);
                break;
            case RadiusOverlayMode.Mortar:
                SetRadiusPreview(_mortarRadiusTiles, MortarRadiusColor, TacticalMapControl.RadiusPreviewFilterMode.Mortar);
                break;
            default:
                ClearRadiusPreview();
                break;
        }
    }

    private void SetRadiusPreview(float radiusTiles, Color color, TacticalMapControl.RadiusPreviewFilterMode filter)
    {
        if (radiusTiles <= 0f)
        {
            ClearRadiusPreview();
            return;
        }

        Map.RadiusPreviewEnabled = true;
        Map.RadiusPreviewTiles = radiusTiles;
        Map.RadiusPreviewColor = color;
        Map.RadiusPreviewFilter = filter;
        Canvas.RadiusPreviewEnabled = true;
        Canvas.RadiusPreviewTiles = radiusTiles;
        Canvas.RadiusPreviewColor = color;
        Canvas.RadiusPreviewFilter = filter;
    }

    private void ClearRadiusPreview()
    {
        Map.RadiusPreviewEnabled = false;
        Map.RadiusPreviewTiles = 0f;
        Map.RadiusPreviewFilter = TacticalMapControl.RadiusPreviewFilterMode.None;
        Canvas.RadiusPreviewEnabled = false;
        Canvas.RadiusPreviewTiles = 0f;
        Canvas.RadiusPreviewFilter = TacticalMapControl.RadiusPreviewFilterMode.None;
    }

    private void UpdateRadiusOverlayButtons()
    {
        var orbitalColor = _radiusOverlayMode == RadiusOverlayMode.OrbitalBombardment ? Color.Green : DefaultButtonTextColor;
        var mortarColor = _radiusOverlayMode == RadiusOverlayMode.Mortar ? Color.Green : DefaultButtonTextColor;

        if (OrbitalRadiusButton != null)
            SetButtonText(OrbitalRadiusButton, Loc.GetString("rmc-tactical-map-radius-ob"), orbitalColor);

        if (MortarRadiusButton != null)
            SetButtonText(MortarRadiusButton, Loc.GetString("rmc-tactical-map-radius-mortar"), mortarColor);
    }

    private void LoadMortarRanges()
    {
        if (TryGetMortarRanges(out var minRange, out var maxRange))
        {
            _mortarMinRange = minRange;
            _mortarMaxRange = maxRange;
            return;
        }

        _mortarMinRange = DefaultMortarMinRange;
        _mortarMaxRange = DefaultMortarMaxRange;
    }

    private bool TryGetMortarRanges(out int minRange, out int maxRange)
    {
        minRange = 0;
        maxRange = 0;

        if (!_prototypes.TryIndex<EntityPrototype>(MortarPrototypeId, out var proto))
            return false;

        if (!proto.TryGetComponent<MortarComponent>(out var mortar, _componentFactory))
            return false;

        minRange = Math.Max(0, mortar.MinimumRange);
        maxRange = Math.Max(minRange, mortar.MaximumRange);
        return maxRange > 0;
    }

    private void LoadHiveRanges()
    {
        _hiveCoreRangeTiles = TryGetRoofingRange(HiveCorePrototypeId, out var coreRange)
            ? coreRange
            : DefaultHiveCoreRangeTiles;
        _hivePylonRangeTiles = TryGetRoofingRange(HivePylonPrototypeId, out var pylonRange)
            ? pylonRange
            : DefaultHivePylonRangeTiles;
    }

    private bool TryGetRoofingRange(EntProtoId prototypeId, out float range)
    {
        range = 0f;

        if (!_prototypes.TryIndex<EntityPrototype>(prototypeId, out var proto))
            return false;

        if (!proto.TryGetComponent<RoofingEntityComponent>(out var roofing, _componentFactory))
            return false;

        range = MathF.Max(0f, roofing.Range);
        return range > 0f;
    }

    private void ApplyHiveOverlayRanges()
