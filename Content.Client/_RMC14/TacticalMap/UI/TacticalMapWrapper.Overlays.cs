    private float GetOrbitalRadius()
    {
        return TryGetOrbitalRadius(out var radius) ? radius : DefaultOrbitalRadiusTiles;
    }

    private float GetMortarRadius()
    {
        return TryGetExplosiveRadius(MortarRadiusPrototypeId, out var radius) ? radius : DefaultMortarRadiusTiles;
    }

    private bool TryGetOrbitalRadius(out float radius)
    {
        radius = 0f;

        if (!_prototypes.TryIndex<EntityPrototype>(OrbitalRadiusPrototypeId, out var proto))
            return false;

        if (!proto.TryGetComponent<OrbitalCannonExplosionComponent>(out var explosion, _componentFactory))
            return false;

        var maxRadius = 0f;
        foreach (var step in explosion.Steps)
        {
            if (step.Type == null || step.Total <= 0f || step.Slope <= 0f)
                continue;

            var stepRadius = IntensityToRadius(step.Total, step.Slope, step.Max);
            if (stepRadius > maxRadius)
                maxRadius = stepRadius;
        }

        if (maxRadius <= 0f)
            return false;

        radius = maxRadius;
        return true;
    }

    private bool TryGetExplosiveRadius(EntProtoId prototypeId, out float radius)
    {
        radius = 0f;

        if (!_prototypes.TryIndex<EntityPrototype>(prototypeId, out var proto))
            return false;

        if (!proto.TryGetComponent<ExplosiveComponent>(out var explosive, _componentFactory))
            return false;

        if (explosive.TotalIntensity <= 0f || explosive.IntensitySlope <= 0f)
            return false;

        radius = IntensityToRadius(explosive.TotalIntensity, explosive.IntensitySlope, explosive.MaxIntensity);
        return radius > 0f;
    }

    private static float IntensityToRadius(float totalIntensity, float slope, float maxIntensity)
    {
        if (totalIntensity <= 0f || slope <= 0f)
            return 0f;

        if (maxIntensity <= 0f)
            return MathF.Cbrt(3f * totalIntensity / (slope * MathF.PI));

        var r0 = maxIntensity / slope;
        var v0 = RadiusToIntensity(r0, slope, maxIntensity);

        if (totalIntensity <= v0)
            return MathF.Cbrt(3f * totalIntensity / (slope * MathF.PI));

        return r0 * (MathF.Sqrt(12f * totalIntensity / v0 - 3f) / 6f + 0.5f);
    }

    private static float RadiusToIntensity(float radius, float slope, float maxIntensity)
    {
        var coneVolume = slope * MathF.PI / 3f * MathF.Pow(radius, 3f);

        if (maxIntensity <= 0f || slope * radius < maxIntensity)
            return coneVolume;

        var h = slope * radius - maxIntensity;
        return coneVolume - h * MathF.PI / 3f * MathF.Pow(h / slope, 2f);
    }

    private void SetupHoverAreaInfo()
    {
        Map.OnHoverAreaInfo += UpdateHoverAreaInfo;
        Canvas.OnHoverAreaInfo += UpdateHoverAreaInfo;
    }

    private void UpdateHoverAreaInfo(TacticalMapAreaInfo? info)
    {
        if (HoverAreaLabel == null)
            return;

        if (info == null)
        {
            HoverAreaLabel.Text = string.Empty;
            if (HoverAreaIcon != null)
                HoverAreaIcon.Visible = false;
            return;
        }

        HoverAreaLabel.Text = Loc.GetString(
            "rmc-tactical-map-hover-area",
            ("area", info.Value.AreaName));
        if (HoverAreaIcon != null)
        {
            HoverAreaIcon.Texture = _entityManager.System<SpriteSystem>()
                .Frame0(new SpriteSpecifier.Rsi(AreaInfoRsiPath, GetAreaIconState(info.Value)));
            HoverAreaIcon.Visible = true;
        }
    }

    private void OnContextMenuRequested(TacticalMapControl source, Vector2i indices, Vector2 screenPosition)
    {
        EnsureContextPopup();

        var showRawCoordinates = IsAdminGhost();
        var info = source.TryGetAreaInfo(indices, out var areaInfo)
            ? areaInfo
            : CreateFallbackAreaInfo(indices);

        var displayCoordinates = showRawCoordinates ? indices : (Vector2i?) null;
        var canCopyCoordinates = displayCoordinates != null;

        var showDeleteMortar = source.IsMortarOverlayTile(indices);

        _contextPopup!.OnCreateLabelPressed = () =>
        {
            source.RequestTacticalLabelEditor(indices);
            _contextPopup?.Close();
        };
        _contextPopup.OnCreateMortarPressed = () =>
        {
            SetMortarOverlay(indices);
            _contextPopup?.Close();
        };
        _contextPopup.OnDeleteMortarPressed = () =>
        {
            Map.ClearMortarOverlay();
            Canvas.ClearMortarOverlay();
            _contextPopup?.Close();
        };
        _contextPopup.OnCopyCoordinatesPressed = () =>
        {
            if (displayCoordinates != null)
                _clipboard.SetText(FormatCoordinates(displayCoordinates.Value));

            _contextPopup?.Close();
        };

        _contextPopup.SetInfo(
            info,
            showRawCoordinates,
            showDeleteMortar,
            showCopyCoordinates: canCopyCoordinates);
        _contextPopup.Open(UIBox2.FromDimensions(screenPosition, new Vector2(1, 1)));
        _contextPopup.SetPositionLast();
    }

    private static string FormatCoordinates(Vector2i coordinates)
    {
        return Loc.GetString(
            "rmc-tactical-map-copy-coords-format",
            ("x", coordinates.X),
            ("y", coordinates.Y));
    }

    private void EnsureContextPopup()
    {
        if (_contextPopup != null)
            return;

        _contextPopup = new TacticalMapContextPopup();
    }

    private static TacticalMapAreaInfo CreateFallbackAreaInfo(Vector2i indices)
    {
        return new TacticalMapAreaInfo(
            indices,
            Loc.GetString("rmc-tacmap-alert-no-area"),
            null,
            null,
            null,
            false,
            false,
            false,
            false,
            false,
            false,
            false,
            false,
            false,
            false,
            false,
            null);
    }

    private bool IsAdminGhost()
    {
        if (_player.LocalEntity == null)
            return false;

        return _entityManager.TryGetComponent(_player.LocalEntity, out GhostComponent? ghost) &&
               ghost.CanGhostInteract;
    }

    private static string GetAreaIconState(TacticalMapAreaInfo info)
    {
        if (!info.HasArea)
            return "roofnull";

        if (!info.OrbitalBombard)
            return "roof4";

        if (!info.Cas)
            return "roof3";

        if (!info.SupplyDrop || !info.MortarFire)
            return "roof2";

        if (!info.MortarPlacement || !info.Lasing || !info.Medevac || !info.Paradropping)
            return "roof1";

        return "roof0";
    }

    private void ToggleOverlayVisibility()
    {
        _overlaysVisible = !_overlaysVisible;
        UpdateOverlayVisibility();
    }

    private void ShowOverlayLegend(BaseButton.ButtonEventArgs args)
    {
        EnsureOverlayLegendPopup();
        var screenPosition = args.Event.PointerLocation.Position;
        _overlayLegendPopup!.Open(UIBox2.FromDimensions(screenPosition, new Vector2(1, 1)));
        _overlayLegendPopup.SetPositionLast();
    }

    private void UpdateOverlayVisibility()
    {
        OverlayContainer.Visible = _overlaysVisible;
        RadiusOverlayContainer.Visible = _overlaysVisible;
        SetButtonText(OverlaysToggleButton, Loc.GetString("rmc-tactical-map-overlays-toggle-button"), DefaultButtonTextColor);
    }

    private void ToggleOverlay(ref bool enabled)
    {
        enabled = !enabled;
        ApplyOverlays();
        UpdateOverlayButtons();
    }

