{
    private void SetupStraightLineMode()
    {
        StraightLineButton.Button.OnPressed += _ => ToggleDrawingMode(DrawingMode.StraightLine);
        UpdateDrawingModeAppearance();
    }

    private void SetupSquareMode()
    {
        SquareButton.Button.OnPressed += _ => ToggleDrawingMode(DrawingMode.Square);
        UpdateDrawingModeAppearance();
    }

    private void SetupEraserMode()
    {
        EraserButton.Button.OnPressed += _ => ToggleDrawingMode(DrawingMode.Eraser);
        UpdateDrawingModeAppearance();
    }

    private void ToggleDrawingMode(DrawingMode mode)
    {
        _currentDrawingMode = (_currentDrawingMode == mode) ? DrawingMode.None : mode;

        if (_currentDrawingMode == DrawingMode.LabelEdit)
        {
            SetLabelsEnabled(true);
            SetLabelState(TacticalMapControl.LabelMode.Tactical);
        }

        ApplyDrawingMode();
        UpdateDrawingModeAppearance();
        UpdateCanvasDrawingState();
    }

    private void ApplyDrawingMode()
    {
        Canvas.StraightLineMode = false;
        Canvas.EraserMode = false;
        Canvas.SquareMode = false;
        Canvas.LabelEditMode = false;
        Map.LabelEditMode = false;

        switch (_currentDrawingMode)
        {
            case DrawingMode.StraightLine:
                Canvas.StraightLineMode = true;
                break;
            case DrawingMode.Square:
                Canvas.SquareMode = true;
                break;
            case DrawingMode.Eraser:
                Canvas.EraserMode = true;
                break;
            case DrawingMode.LabelEdit:
                Canvas.LabelEditMode = true;
                Map.LabelEditMode = true;
                break;
            case DrawingMode.None:
                break;
        }
    }

    private void UpdateDrawingModeAppearance()
    {
        UpdateStraightLineButtonAppearance();
        UpdateSquareButtonAppearance();
        UpdateEraserButtonAppearance();
        UpdateLabelEditButtonAppearance();
    }

    private void UpdateStraightLineButtonAppearance()
    {
        if (StraightLineButton != null)
        {
            var color = _currentDrawingMode == DrawingMode.StraightLine ? Color.Green : DefaultButtonTextColor;
            SetButtonTextColor(StraightLineButton, color);
        }
    }

    private void UpdateLabelEditButtonAppearance()
    {
        if (LabelEditButton != null)
        {
            var color = _currentDrawingMode == DrawingMode.LabelEdit ? Color.Green : DefaultButtonTextColor;
            SetButtonTextColor(LabelEditButton, color);
        }
    }

    private void UpdateSquareButtonAppearance()
    {
        if (SquareButton != null)
        {
            var color = _currentDrawingMode == DrawingMode.Square ? Color.Green : DefaultButtonTextColor;
            SetButtonTextColor(SquareButton, color);
        }
    }

    private void UpdateEraserButtonAppearance()
    {
        if (EraserButton != null)
        {
            var color = _currentDrawingMode == DrawingMode.Eraser ? Color.Green : DefaultButtonTextColor;
            SetButtonTextColor(EraserButton, color);
        }
    }

    private void OnUndoPressed()
    {
        if (Canvas.UndoLastStroke())
        {
            MarkCanvasDirty();
        }
    }

    private void ToggleCurrentLabels()
    {
        SetLabelsEnabled(!_labelsEnabled);
    }

    private void CycleLabelTypes()
    {
        switch (_currentLabelState)
        {
            case TacticalMapControl.LabelMode.All:
                SetLabelState(TacticalMapControl.LabelMode.Area);
                break;
            case TacticalMapControl.LabelMode.Tactical:
                SetLabelState(TacticalMapControl.LabelMode.All);
                break;
            case TacticalMapControl.LabelMode.Area:
                SetLabelState(TacticalMapControl.LabelMode.Tactical);
                break;
            case TacticalMapControl.LabelMode.None:
                SetLabelState(TacticalMapControl.LabelMode.All);
                break;
        }
    }

    private void ToggleFollowPlayer()
    {
        _followingPlayer = !_followingPlayer;
        UpdateFollowButtonText();

        if (_followingPlayer)
            CenterOnPlayer();
    }

    private void ResetView()
    {
        _currentZoomFactor = 1.0f;
        _currentPanOffset = Vector2.Zero;
        ApplyViewStateToControls();

        if (_followingPlayer)
        {
            _followingPlayer = false;
            UpdateFollowButtonText();
            InvalidatePlayerCache();
        }
    }

    private void CenterOnPlayer()
    {
        if (TryFindPlayerBlip(out Vector2i playerIndices))
        {
            if (Map.CenterOnPosition(playerIndices))
            {
                _currentZoomFactor = Map.GetCurrentZoomFactor();
                _currentPanOffset = Map.GetCurrentPanOffset();
                ApplyViewStateToControls();
                _lastPlayerPosition = playerIndices;
            }
        }
    }

    private void SetLabelState(TacticalMapControl.LabelMode newState, bool saveToConfig = false)
    {
        _currentLabelState = newState;
        ApplyLabelMode();
    }

    private void SetLabelsEnabled(bool enabled)
    {
        _labelsEnabled = enabled;
        ApplyLabelMode();
    }

    private void ApplyLabelMode()
    {
        var mode = _labelsEnabled ? _currentLabelState : TacticalMapControl.LabelMode.None;
        Map.CurrentLabelMode = mode;
        Canvas.CurrentLabelMode = mode;

        UpdateLabelsButtonAppearance();
    }

    private void UpdateLabelsButtonAppearance()
    {
        Color color;
        string text;

        switch (_currentLabelState)
        {
            case TacticalMapControl.LabelMode.All:
                text = Loc.GetString("rmc-tactical-map-labels-mode-all");
                color = Color.FromHex("#8AB4FF");
                break;
            case TacticalMapControl.LabelMode.Area:
                text = Loc.GetString("ui-tactical-map-labels-mode-area");
                color = Color.Orange;
                break;
            case TacticalMapControl.LabelMode.Tactical:
                text = Loc.GetString("ui-tactical-map-labels-mode-tactical");
                color = Color.Green;
                break;
            default:
                text = Loc.GetString("rmc-tactical-map-labels-mode-all");
                color = DefaultButtonTextColor;
                break;
        }

        if (!_labelsEnabled)
        {
            text = Loc.GetString("rmc-tactical-map-labels-mode-off", ("mode", text));
            color = Color.Red;
        }

        if (LabelsButton != null)
            SetButtonText(LabelsButton, text, color);

    }

    private void UpdatePlayerFollowing(float deltaSeconds)
    {
        if (!_followingPlayer)
            return;

        _followUpdateTimer += deltaSeconds;

        if (_followUpdateTimer < FollowUpdateInterval)
            return;

        _followUpdateTimer = 0f;

        if (TryFindPlayerBlip(out Vector2i currentPlayerPosition) &&
            _lastPlayerPosition != currentPlayerPosition)
        {
            if (Map.CenterOnPosition(currentPlayerPosition))
            {
                _currentZoomFactor = Map.GetCurrentZoomFactor();
                _currentPanOffset = Map.GetCurrentPanOffset();
                ApplyViewStateToControls();
                _lastPlayerPosition = currentPlayerPosition;
            }
        }
    }

    private void UpdateCooldownBar()
    {
        if (!_canDraw || !IsGlobalDrawLayer())
        {
            if (UpdateUpdateFeedback())
                return;
            UpdateCanvasButton.Disabled = false;
            CooldownBar.Visible = false;
            return;
        }

        IGameTiming time = IoCManager.Resolve<IGameTiming>();
        var cooldown = NextUpdateAt - time.CurTime;

        if (cooldown < TimeSpan.Zero)
        {
            if (UpdateUpdateFeedback())
                return;
            UpdateCanvasButton.Disabled = false;
            CooldownBar.Visible = false;
            return;
        }

        UpdateCanvasButton.Disabled = true;
        CooldownBar.Visible = true;
        CooldownBar.MinValue = (float)LastUpdateAt.TotalSeconds;
        CooldownBar.MaxValue = (float)NextUpdateAt.TotalSeconds;
        CooldownBar.Value = (float)(LastUpdateAt.TotalSeconds + NextUpdateAt.TotalSeconds - time.CurTime.TotalSeconds);
        CooldownLabel.Text = Loc.GetString("ui-tactical-map-cooldown-seconds", ("seconds", (int)cooldown.TotalSeconds));
    }

    private bool UpdateUpdateFeedback()
    {
        if (_updateFeedbackUntil == TimeSpan.Zero)
            return false;

        var time = IoCManager.Resolve<IGameTiming>();
        if (time.CurTime >= _updateFeedbackUntil)
        {
            _updateFeedbackUntil = TimeSpan.Zero;
            return false;
        }

        CooldownBar.Visible = true;
        CooldownBar.MinValue = 0f;
        CooldownBar.MaxValue = UpdateFeedbackSeconds;
        var remaining = (float)(_updateFeedbackUntil - time.CurTime).TotalSeconds;
        CooldownBar.Value = remaining;
        CooldownLabel.Text = Loc.GetString("rmc-tactical-map-updated");
        UpdateCanvasButton.Disabled = false;
        return true;
    }

    private bool IsGlobalDrawLayer()
    {
        EntProtoId<TacticalMapLayerComponent>? layer = _lastActiveLayer;
        if (layer == null && _lastDrawLayers.Count > 0)
            layer = _lastDrawLayers[0];

        return layer != null && _layers.TryGet(layer.Value, out var definition) && definition.CanUpdateBlips;
    }

    private void UpdateBlipStaleAlpha()
    {
        var alpha = 1f;

        if (_blipStaleEnabled)
        {
            IGameTiming time = IoCManager.Resolve<IGameTiming>();
            // older snapshots fade down slowly.
            var ageSeconds = MathF.Max(0f, (float)(time.CurTime - _blipStaleSince).TotalSeconds);

            if (ageSeconds <= BlipStaleFadeStartSeconds)
                alpha = 1f;
            else if (ageSeconds >= BlipStaleFadeEndSeconds)
                alpha = BlipStaleMinAlpha;
            else
            {
                var t = (ageSeconds - BlipStaleFadeStartSeconds) / (BlipStaleFadeEndSeconds - BlipStaleFadeStartSeconds);
                alpha = 1f - (1f - BlipStaleMinAlpha) * t;
            }
        }

        if (MathF.Abs(alpha - _blipStaleAlpha) < 0.01f)
            return;

        _blipStaleAlpha = alpha;
        Map.BlipStaleAlpha = alpha;
        Canvas.BlipStaleAlpha = alpha;
    }
}
