    public void UpdateMapList(IReadOnlyList<TacticalMapMapInfo> maps, NetEntity activeMap)
    {
        // rebuild server-owned map options without echoing selection events.
        _suppressMapSelection = true;
        MapSelectButton.Clear();

        var selectedId = -1;
        for (var i = 0; i < maps.Count; i++)
        {
            var map = maps[i];
            MapSelectButton.AddItem(map.DisplayName, i);
            MapSelectButton.SetItemMetadata(i, map.Map);
            if (map.Map == activeMap)
                selectedId = i;
        }

        MapSelectionRow.Visible = maps.Count > 1;
        MapSelectButton.Disabled = maps.Count <= 1;

        if (maps.Count > 0)
            MapSelectButton.SelectId(selectedId >= 0 ? selectedId : 0);

        _suppressMapSelection = false;
    }

    public void UpdateObjectives(Dictionary<SquadObjectiveType, string> objectives)
    {
        var hasAnyObjective = objectives.Any(pair => !string.IsNullOrWhiteSpace(pair.Value));
        if (objectives.Count == 0 || !hasAnyObjective)
        {
            ObjectivesContainer.Visible = false;
            return;
        }

        ObjectivesContainer.Visible = true;
        ObjectivesList.Visible = _objectivesVisible;
        SetObjectivesToggleText();

        foreach (var objectiveType in Enum.GetValues<SquadObjectiveType>())
        {
            var objectiveText = objectives.GetValueOrDefault(objectiveType, string.Empty);
            var objectiveName = objectiveType switch
            {
                SquadObjectiveType.Primary => Loc.GetString("rmc-overwatch-console-objective-primary"),
                SquadObjectiveType.Secondary => Loc.GetString("rmc-overwatch-console-objective-secondary"),
                _ => objectiveType.ToString()
            };

            var displayText = string.IsNullOrWhiteSpace(objectiveText)
                ? $"{objectiveName}: {Loc.GetString("rmc-squad-info-none")}"
                : $"{objectiveName}: {FormattedMessage.EscapeText(objectiveText)}";

            var objectiveLabel = objectiveType == SquadObjectiveType.Primary ? PrimaryObjectiveLabel : SecondaryObjectiveLabel;
            objectiveLabel.Text = displayText;
        }
    }

    private void ToggleObjectivesVisibility()
    {
        _objectivesVisible = !_objectivesVisible;
        ObjectivesList.Visible = _objectivesVisible;
        SetObjectivesToggleText();
    }

    private void SetObjectivesToggleText()
    {
        var text = _objectivesVisible ? Loc.GetString("rmc-tactical-map-layer-visibility-hide") : Loc.GetString("rmc-tactical-map-layer-visibility-show");
        SetButtonText(ObjectivesToggleButton, text, DefaultButtonTextColor);
    }

    public void UpdateDrawLayerList(IReadOnlyList<EntProtoId<TacticalMapLayerComponent>> layers, EntProtoId<TacticalMapLayerComponent>? activeLayer)
    {
        _lastDrawLayers.Clear();
        _lastDrawLayers.AddRange(layers);
        var activeChanged = _lastActiveLayer != activeLayer;
        _lastActiveLayer = activeLayer;
        if (activeChanged)
        {
            // active layer changes replace the editable canvas snapshot.
            MarkCanvasSynced();
        }

        _suppressLayerSelection = true;
        LayerSelectButton.Clear();
        UpdateActiveLayerIndicator(layers, activeLayer);

        if (!_canDraw || layers.Count == 0)
        {
            LayerSelectionRow.Visible = false;
            _suppressLayerSelection = false;
            return;
        }

        if (layers.Count <= 1)
        {
            LayerSelectionRow.Visible = false;
            _suppressLayerSelection = false;
            return;
        }

        LayerSelectionRow.Visible = true;

        var selectedId = 0;
        var id = 0;

        foreach (var layer in layers)
        {
            LayerSelectButton.AddItem(GetLayerName(layer), id);
            LayerSelectButton.SetItemMetadata(id, layer);
            if (activeLayer == layer)
                selectedId = id;
            id++;
        }

        LayerSelectButton.SelectId(selectedId);
        _suppressLayerSelection = false;
    }

    public void UpdateLayerList(IReadOnlyList<EntProtoId<TacticalMapLayerComponent>> layers, EntProtoId<TacticalMapLayerComponent>? activeLayer)
    {
        _suppressLayerSelection = true;
        LayerSelectButton.Clear();
        UpdateActiveLayerIndicator(layers, activeLayer);

        if (layers.Count <= 1)
        {
            LayerSelectionRow.Visible = false;
            _suppressLayerSelection = false;
            return;
        }

        LayerSelectionRow.Visible = true;

        var selectedId = 0;
        var id = 0;
        LayerSelectButton.AddItem(Loc.GetString("rmc-tactical-map-layer-all"), id);
        id++;

        foreach (var layer in layers)
        {
            LayerSelectButton.AddItem(GetLayerName(layer), id);
            LayerSelectButton.SetItemMetadata(id, layer);
            if (activeLayer == layer)
                selectedId = id;
            id++;
        }

        LayerSelectButton.SelectId(selectedId);
        _suppressLayerSelection = false;
    }

    public void UpdateLayerVisibilityList(IReadOnlyList<EntProtoId<TacticalMapLayerComponent>> layers, IReadOnlyList<EntProtoId<TacticalMapLayerComponent>> visibleLayers)
    {
        // layer visibility is server-owned, local clicks request changes.
        var incomingLayers = layers.ToList();
        var wasExpanded = _layerVisibilityExpanded || LayerVisibilityGrid.Visible;
        var sameLayerList = _availableLayers.Count == incomingLayers.Count;
        if (sameLayerList)
        {
            for (var i = 0; i < incomingLayers.Count; i++)
            {
                if (_availableLayers[i] != incomingLayers[i])
                {
                    sameLayerList = false;
                    break;
                }
            }
        }

        _availableLayers.Clear();
        _availableLayers.AddRange(incomingLayers);
        _visibleLayerSet.Clear();
        foreach (var layer in visibleLayers)
        {
            _visibleLayerSet.Add(layer);
        }

        _suppressLayerVisibilitySelection = true;
        if (!sameLayerList)
        {
            LayerVisibilityGrid.RemoveAllChildren();
            _layerVisibilityButtons.Clear();
        }

        if (incomingLayers.Count <= 1)
        {
            LayerVisibilityContainer.Visible = false;
            UpdateLayerVisibilityToggle();
            _suppressLayerVisibilitySelection = false;
            return;
        }

        LayerVisibilityContainer.Visible = true;
        _layerVisibilityExpanded = wasExpanded;

        var summary = Loc.GetString("rmc-tactical-map-layer-visibility-summary",
            ("selected", _visibleLayerSet.Count),
            ("total", incomingLayers.Count));
        _layerVisibilitySummary = summary;
        UpdateLayerVisibilityColumns();

        foreach (var layer in incomingLayers)
        {
            if (!_layerVisibilityButtons.TryGetValue(layer, out var button))
            {
                button = new TacticalMapButton
                {
                    MinHeight = 20,
                    MinWidth = LayerVisibilityButtonMinWidth
                };

                button.Button.OnPressed += _ =>
                {
                    if (_suppressLayerVisibilitySelection)
                        return;

                    ToggleVisibleLayer(layer);
                };

                _layerVisibilityButtons[layer] = button;
                LayerVisibilityGrid.AddChild(button);
            }

            UpdateLayerVisibilityButton(layer, button);
        }

        UpdateLayerVisibilityToggle();
        _suppressLayerVisibilitySelection = false;
    }

    private void UpdateLayerVisibilityButton(EntProtoId<TacticalMapLayerComponent> layer, TacticalMapButton button)
    {
        var selected = _visibleLayerSet.Contains(layer);
        var activeOverride = _canDraw && _drawingEnabled && !selected &&
            _lastActiveLayer != null && _lastActiveLayer.Value == layer;
        var prefix = selected ? "[X] " : "[ ] ";
        var text = prefix + GetLayerName(layer);
        var color = selected
            ? Color.Green
            : (activeOverride ? ActiveLayerOverrideTextColor : DisabledLayerTextColor);
        button.Button.HoveredTextColor = color;
        SetButtonText(button, text, color);
    }

    private void RefreshLayerVisibilityButtonColors()
    {
        if (_availableLayers.Count == 0 || _layerVisibilityButtons.Count == 0)
            return;

        foreach (var layer in _availableLayers)
        {
            if (_layerVisibilityButtons.TryGetValue(layer, out var button))
                UpdateLayerVisibilityButton(layer, button);
        }
    }

    private void UpdateLayerVisibilityColumnsIfNeeded()
    {
        if (!LayerVisibilityContainer.Visible)
            return;

        var width = LayerVisibilityContainer.Width;
        if (MathF.Abs(width - _lastLayerVisibilityWidth) < 0.5f)
            return;

        _lastLayerVisibilityWidth = width;
        UpdateLayerVisibilityColumns();
    }

    private void SetupMapSelector()
    {
        MapSelectButton.OnItemSelected += args =>
        {
            if (_suppressMapSelection)
                return;

            if (MapSelectButton.GetItemMetadata(args.Id) is NetEntity map)
                MapSelected?.Invoke(map);
        };
    }

    private void SetupLayerSelector()
    {
        LayerSelectButton.OnItemSelected += args =>
        {
            if (_suppressLayerSelection)
                return;

            EntProtoId<TacticalMapLayerComponent>? selected = null;
            if (LayerSelectButton.GetItemMetadata(args.Id) is EntProtoId<TacticalMapLayerComponent> layer)
                selected = layer;

            LayerSelected?.Invoke(selected);
        };
    }

    private void SetupLayerVisibilitySelector()
    {
        LayerVisibilityToggleButton.Button.OnPressed += _ =>
        {
            _layerVisibilityExpanded = !_layerVisibilityExpanded;
            UpdateLayerVisibilityToggle();
        };
    }

    private void ToggleVisibleLayer(EntProtoId<TacticalMapLayerComponent> layer)
    {
        _layerVisibilityExpanded = true;
        if (_visibleLayerSet.Contains(layer))
        {
            if (_visibleLayerSet.Count <= 1)
                return;

            _visibleLayerSet.Remove(layer);
        }
        else
        {
            _visibleLayerSet.Add(layer);
        }

        UpdateLayerVisibilityList(_availableLayers, _visibleLayerSet.ToList());
        VisibleLayersChanged?.Invoke(_visibleLayerSet.ToList());
    }

    private void UpdateLayerVisibilityToggle()
    {
        LayerVisibilityGrid.Visible = _layerVisibilityExpanded;
        var actionText = _layerVisibilityExpanded
            ? Loc.GetString("rmc-tactical-map-layer-visibility-hide")
            : Loc.GetString("rmc-tactical-map-layer-visibility-show");
        var text = string.IsNullOrWhiteSpace(_layerVisibilitySummary)
            ? actionText
            : $"{_layerVisibilitySummary} {actionText}";
        SetButtonText(LayerVisibilityToggleButton, text, DefaultButtonTextColor);
    }

    private void UpdateLayerVisibilityColumns()
    {
        var availableWidth = LayerVisibilityContainer.Width;
        var columns = 3;
        if (availableWidth > 0f)
        {
            const float separation = 4f;
            var cellWidth = LayerVisibilityButtonMinWidth + separation;
            columns = Math.Clamp((int)MathF.Floor((availableWidth + separation) / cellWidth), 2, 6);
        }

        LayerVisibilityGrid.Columns = columns;
    }

    private string GetLayerName(EntProtoId<TacticalMapLayerComponent> layer)
    {
        if (_layers.TryGet(layer, out var prototype))
            return Loc.GetString(prototype.Name);

        return layer.Id;
    }

    private void UpdateActiveLayerIndicator(
        IReadOnlyList<EntProtoId<TacticalMapLayerComponent>> layers,
        EntProtoId<TacticalMapLayerComponent>? activeLayer)
    {
        EntProtoId<TacticalMapLayerComponent>? displayLayer = activeLayer;
        if (displayLayer == null && layers.Count > 0)
            displayLayer = layers[0];

        if (displayLayer == null)
        {
            ActiveLayerRow.Visible = false;
            return;
        }

        ActiveLayerRow.Visible = true;
        ActiveLayerLabel.Text = Loc.GetString("rmc-tactical-map-layer-viewing",
            ("layer", GetLayerName(displayLayer.Value)));
    }
}
