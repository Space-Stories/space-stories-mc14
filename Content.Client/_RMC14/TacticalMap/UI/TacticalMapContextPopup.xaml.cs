using System;
using System.Collections.Generic;
using System.Linq;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.IoC;
using Robust.Shared.GameObjects;
using Robust.Shared.Localization;
using Robust.Shared.Utility;
using Content.Client._RMC14.TacticalMap.Controls;

namespace Content.Client._RMC14.TacticalMap.UI;

[GenerateTypedNameReferences]
public sealed partial class TacticalMapContextPopup : Popup
{
    private readonly SpriteSystem _spriteSystem;

    private static readonly ResPath AreaInfoRsiPath = new("/Textures/_RMC14/Structures/Machines/ceiling.rsi");

    public Action? OnCreateLabelPressed;
    public Action? OnCreateMortarPressed;
    public Action? OnDeleteMortarPressed;
    public Action? OnCopyCoordinatesPressed;

    public TacticalMapContextPopup()
    {
        RobustXamlLoader.Load(this);
        _spriteSystem = IoCManager.Resolve<IEntityManager>().System<SpriteSystem>();

        if (Background.PanelOverride is StyleBoxFlat box)
        {
            box.BackgroundColor = Color.FromHex("#0B0F14").WithAlpha(0.75f);
            box.BorderColor = Color.FromHex("#0B0F14").WithAlpha(0.1f);
            box.BorderThickness = new Thickness(1);
        }

        CreateLabelButton.Button.OnPressed += _ => OnCreateLabelPressed?.Invoke();
        CreateMortarButton.Button.OnPressed += _ => OnCreateMortarPressed?.Invoke();
        DeleteMortarButton.Button.OnPressed += _ => OnDeleteMortarPressed?.Invoke();
        CopyCoordinatesButton.Button.OnPressed += _ => OnCopyCoordinatesPressed?.Invoke();

        UserInterfaceManager.ModalRoot.AddChild(this);
    }

    public void SetInfo(
        TacticalMapAreaInfo info,
        bool showCoordinates,
        bool showDeleteMortar,
        bool showCopyCoordinates)
    {
        AreaNameLabel.Text = info.AreaName;

        AreaIcon.Texture = _spriteSystem.Frame0(new SpriteSpecifier.Rsi(AreaInfoRsiPath, GetAreaIconState(info)));

        SetInfoLine(CoordinatesLabel, Loc.GetString("rmc-tactical-map-context-coords", ("x", info.Indices.X), ("y", info.Indices.Y)), showCoordinates);
        SetInfoLine(AreaIdLabel, Loc.GetString("rmc-tactical-map-context-id", ("id", info.AreaId ?? string.Empty)), showCoordinates && !string.IsNullOrWhiteSpace(info.AreaId));
        SetInfoLine(LinkedLzLabel, Loc.GetString("rmc-tactical-map-context-linked-lz", ("lz", info.LinkedLz ?? string.Empty)), !string.IsNullOrWhiteSpace(info.LinkedLz));
        SetInfoLine(TacticalLabel, Loc.GetString("rmc-tactical-map-context-tactical-label", ("label", info.TacticalLabel ?? string.Empty)), !string.IsNullOrWhiteSpace(info.TacticalLabel));
        SetInfoLine(RegionLabel, Loc.GetString("rmc-tactical-map-context-area-label", ("label", info.AreaLabel ?? string.Empty)), !string.IsNullOrWhiteSpace(info.AreaLabel));

        var allowed = new List<string>();
        var blocked = new List<string>();
        if (info.HasArea)
            BuildActionLists(info, out allowed, out blocked);

        var labelKey = string.IsNullOrWhiteSpace(info.TacticalLabel)
            ? "ui-tactical-map-label-dialog-create-title"
            : "ui-tactical-map-label-dialog-edit-title";
        CreateLabelButton.Text = Loc.GetString(labelKey);
        CreateMortarButton.Text = Loc.GetString("rmc-tactical-map-create-mortar");
        CreateMortarButton.Disabled = info.HasArea && !info.MortarPlacement;
        DeleteMortarButton.Text = Loc.GetString("rmc-tactical-map-remove-mortar");
        DeleteMortarButton.Visible = showDeleteMortar;
        CopyCoordinatesButton.Text = Loc.GetString("rmc-tactical-map-copy-coordinates");
        CopyCoordinatesButton.Visible = showCopyCoordinates;
        AddActionRow(allowed, blocked);
    }

    private static void SetInfoLine(Label label, string text, bool visible)
    {
        label.Text = text;
        label.ToolTip = text;
        label.Visible = visible;
    }

    private static void BuildActionLists(TacticalMapAreaInfo info, out List<string> allowed, out List<string> blocked)
    {
        allowed = new List<string>();
        blocked = new List<string>();

        AddAction(info.OrbitalBombard, "rmc-tactical-map-action-ob", allowed, blocked);
        AddAction(info.Cas, "rmc-tactical-map-action-cas", allowed, blocked);
        AddAction(info.SupplyDrop, "rmc-tactical-map-action-supply", allowed, blocked);
        AddAction(info.MortarFire, "rmc-tactical-map-action-mortar-fire", allowed, blocked);
        AddAction(info.MortarPlacement, "rmc-tactical-map-action-mortar-place", allowed, blocked);
        AddAction(info.Lasing, "rmc-tactical-map-action-lase", allowed, blocked);
        AddAction(info.Medevac, "rmc-tactical-map-action-medevac", allowed, blocked);
        AddAction(info.Paradropping, "rmc-tactical-map-action-paradrop", allowed, blocked);
        AddAction(info.Fulton, "rmc-tactical-map-action-fulton", allowed, blocked);
        AddAction(info.LandingZone, "rmc-tactical-map-action-landing-zone", allowed, blocked);
    }

    private void AddActionRow(List<string> allowed, List<string> blocked)
    {
        AllowedActions.Visible = allowed.Count > 0;
        BlockedActions.Visible = blocked.Count > 0;
        AllowedLabel.Text = string.Join("\n", allowed.Select(action => "+ " + action));
        BlockedLabel.Text = string.Join("\n", blocked.Select(action => "- " + action));
        ButtonColumn.Margin = allowed.Count > 0 || blocked.Count > 0 ? new Thickness(6, 0, 0, 0) : default;
    }

    private static void AddAction(bool allowedAction, string locKey, List<string> allowed, List<string> blocked)
    {
        var name = Loc.GetString(locKey);
        if (allowedAction)
            allowed.Add(name);
        else
            blocked.Add(name);
    }

    private static string GetAreaIconState(TacticalMapAreaInfo info)
    {
        if (!info.HasArea)
            return "roofnull";

        if (!info.OrbitalBombard)
            return "roof4";

        if (!info.Cas)
            return "roof3";

        if (!info.SupplyDrop || !info.MortarFire)
            return "roof2";

        if (!info.MortarPlacement || !info.Lasing || !info.Medevac || !info.Paradropping)
            return "roof1";

        return "roof0";
    }
}
