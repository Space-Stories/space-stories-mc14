public sealed partial class TacticalMapWrapper
{
    public event Action<Vector2i, TacticalMapLabelData?>? PersonalLabelChanged;

    private readonly Dictionary<Vector2i, TacticalMapLabelData> _sharedMapLabels = new();
    private readonly Dictionary<Vector2i, TacticalMapLabelData> _personalLabels = new();

    public void UpdateMapLabels(IReadOnlyDictionary<Vector2i, TacticalMapLabelData>? shared,
        IReadOnlyDictionary<Vector2i, TacticalMapLabelData>? personal)
    {
        _sharedMapLabels.Clear();
        _personalLabels.Clear();
        if (shared != null)
        {
            foreach (var (position, label) in shared)
                _sharedMapLabels[position] = label;
        }
        if (personal != null)
        {
            foreach (var (position, label) in personal)
                _personalLabels[position] = label;
        }
        RebuildMapLabels();
    }

    private void RebuildMapLabels()
    {
        Map.UpdateTacticalLabels(_sharedMapLabels);
        foreach (var (position, label) in _personalLabels)
            Map.TacticalLabels[position] = label;
    }

    private void SetMapLabel(Vector2i position, TacticalMapLabelData? label)
    {
        if (_canDraw)
        {
            if (label is { } drawing)
            {
                Canvas.TacticalLabels[position] = drawing;
                Map.TacticalLabels[position] = drawing;
            }
            else
            {
                Canvas.TacticalLabels.Remove(position);
                Map.TacticalLabels.Remove(position);
            }
            MarkCanvasDirty();
            return;
        }

        if (label is { } value)
            _personalLabels[position] = value;
        else
            _personalLabels.Remove(position);

        PersonalLabelChanged?.Invoke(position, label);
        RebuildMapLabels();
    }

    public void UpdateCanvasBackground()
    {
        // canvas background shows visible-layer context behind the active layer.
        Canvas.BackgroundLines.Clear();
        if (Map.Lines.Count > 0)
        {
            if (Canvas.Lines.Count == 0)
            {
                Canvas.BackgroundLines.AddRange(Map.Lines);
            }
            else
            {
                var activeSet = new HashSet<TacticalMapLine>(Canvas.Lines);
                foreach (var line in Map.Lines)
                {
                    if (!activeSet.Contains(line))
                        Canvas.BackgroundLines.Add(line);
                }
            }
        }

        Canvas.BackgroundLabels.Clear();
        if (Map.TacticalLabels.Count > 0)
        {
            foreach (var (pos, label) in Map.TacticalLabels)
            {
                if (!Canvas.TacticalLabels.ContainsKey(pos))
                    Canvas.BackgroundLabels[pos] = label;
            }
        }
    }

    public void SetLineLimit(int limit)
    {
        Canvas.LineLimit = limit;
    }

    public void SetBlipStaleState(bool enabled, TimeSpan lastUpdateAt)
    {
        _blipStaleEnabled = enabled;
        _blipStaleSince = lastUpdateAt;
        _blipStaleAlpha = -1f;
        UpdateBlipStaleAlpha();
    }

    public void SetCanvasAccess(bool canDraw)
    {
        _canDraw = canDraw;
        if (!canDraw)
        {
            _canvasDirty = false;
            _pendingCanvasUpdate = null;
        }
        UpdateCanvasDrawingState();
        ApplyFocusVisibility();
        if (_lastDrawLayers.Count > 0)
            UpdateDrawLayerList(_lastDrawLayers, _lastActiveLayer);
    }

    public void OnUserInteraction()
    {
        if (_followingPlayer)
        {
            _followingPlayer = false;
            UpdateFollowButtonText();
            InvalidatePlayerCache();
        }
    }

    private void SetupLabelEditMode()
    {
        Map.OnCreateLabel += (position, text) => {
            var labelData = new TacticalMapLabelData(text, _colors[_currentSelectedColorIndex].Color);
            SetMapLabel(position, labelData);
        };

        Canvas.OnCreateLabel += (position, text) => {
            var labelData = new TacticalMapLabelData(text, _colors[_currentSelectedColorIndex].Color);
            Canvas.TacticalLabels[position] = labelData;
            Map.TacticalLabels[position] = labelData;
            MarkCanvasDirty();
        };

        Map.OnEditLabel += (position, text) => {
            var color = Map.TacticalLabels.TryGetValue(position, out var existing)
                ? existing.Color
                : _colors[_currentSelectedColorIndex].Color;
            SetMapLabel(position, new TacticalMapLabelData(text, color));
        };

        Canvas.OnEditLabel += (position, text) => {
            var color = Canvas.TacticalLabels.TryGetValue(position, out var existing)
                ? existing.Color
                : _colors[_currentSelectedColorIndex].Color;
            var labelData = new TacticalMapLabelData(text, color);
            Canvas.TacticalLabels[position] = labelData;
            Map.TacticalLabels[position] = labelData;
            MarkCanvasDirty();
        };

        Map.OnDeleteLabel += position => {
            SetMapLabel(position, null);
        };

        Canvas.OnDeleteLabel += position => {
            Canvas.TacticalLabels.Remove(position);
            Map.TacticalLabels.Remove(position);
            MarkCanvasDirty();
        };

        Map.OnMoveLabel += (oldPos, newPos) => {
            if (Map.TacticalLabels.TryGetValue(oldPos, out var data))
            {
                SetMapLabel(oldPos, null);
                SetMapLabel(newPos, data);
            }
        };

        Canvas.OnMoveLabel += (oldPos, newPos) => {
            if (Canvas.TacticalLabels.TryGetValue(oldPos, out var data))
            {
                Canvas.TacticalLabels.Remove(oldPos);
                Canvas.TacticalLabels[newPos] = data;
                Map.TacticalLabels.Remove(oldPos);
                Map.TacticalLabels[newPos] = data;
                MarkCanvasDirty();
            }
        };

        LabelEditButton.Button.OnPressed += _ => ToggleDrawingMode(DrawingMode.LabelEdit);
        UpdateDrawingModeAppearance();
    }

    private void SetupColorButtons()
    {
        ColorButtonsContainer.RemoveAllChildren();
        _colorButtons.Clear();
        var buttonBorder = Color.FromHex("#2C3440");

        for (int i = 0; i < _colors.Count; i++)
        {
            var index = i;
            (string name, Color color) = _colors[i];

            var button = new TacticalMapButton
            {
                MinSize = new Vector2(22, 22),
                MaxSize = new Vector2(22, 22),
                Margin = new Thickness(2),
                Text = string.Empty,
            };

            button.BackgroundColor = color;
            button.BorderThickness = new Thickness(1);
            button.BorderColor = buttonBorder;
            button.Button.ToolTip = name;
            button.Button.OnPressed += _ => SelectColorButton(index);

            _colorButtons.Add(button);
            ColorButtonsContainer.AddChild(button);
        }

        _colorSelected = false;
        _drawingEnabled = false;
        UpdateColorButtonAppearance();
    }

    private void SelectColorButton(int index)
    {
        if (index < 0 || index >= _colors.Count || index >= _colorButtons.Count)
            return;

        if (_colorSelected && _currentSelectedColorIndex == index)
        {
            _drawingEnabled = !_drawingEnabled;
            UpdateCanvasDrawingState();
            return;
        }

        _currentSelectedColorIndex = index;
        _colorSelected = true;
        _drawingEnabled = true;
        Canvas.Color = _colors[index].Color;
        UpdateColorButtonAppearance();
        UpdateCanvasDrawingState();
    }

    private void UpdateColorButtonAppearance()
    {
        var defaultBorder = Color.FromHex("#2C3440");
        for (int i = 0; i < _colorButtons.Count; i++)
        {
            var selected = _drawingEnabled && _colorSelected && i == _currentSelectedColorIndex;
            _colorButtons[i].BorderColor = selected ? Color.White : defaultBorder;
        }
    }

    private void SetupAreaLabels()
    {
        LabelsButton.Button.OnPressed += _ => ToggleCurrentLabels();

        LabelsButton.Button.OnKeyBindDown += args =>
        {
            if (args.Function == EngineKeyFunctions.UIRightClick)
            {
                CycleLabelTypes();
                args.Handle();
            }
        };

        _labelsEnabled = true;
        SetLabelState(TacticalMapControl.LabelMode.All);
    }

    private void SetupBlipSize()
    {
        var initialBlipSize = 0.9f;
        BlipSizeSlider.Value = initialBlipSize;
        BlipSizeLabel.Text = Loc.GetString("ui-tactical-map-blip-size-label", ("size", initialBlipSize.ToString("F1")));

        Map.BlipSizeMultiplier = initialBlipSize;
        Canvas.BlipSizeMultiplier = initialBlipSize;

        BlipSizeSlider.OnValueChanged += args =>
        {
            var value = (float)args.Value;
            BlipSizeLabel.Text = Loc.GetString("ui-tactical-map-blip-size-label", ("size", value.ToString("F1")));
            Map.BlipSizeMultiplier = value;
            Canvas.BlipSizeMultiplier = value;
            _currentBlipSizeMultiplier = value;
        };
    }

    private void SetupLineThickness()
    {
        var initialThickness = 2.0f;
        LineThicknessSlider.Value = initialThickness;
        LineThicknessLabel.Text = Loc.GetString("ui-tactical-map-line-width-label", ("width", initialThickness.ToString("F1")));

        Map.LineThickness = initialThickness;
        Canvas.LineThickness = initialThickness;

        LineThicknessSlider.OnValueChanged += args =>
        {
            var value = (float)args.Value;
            LineThicknessLabel.Text = Loc.GetString("ui-tactical-map-line-width-label", ("width", value.ToString("F1")));
            Map.LineThickness = value;
            Canvas.LineThickness = value;
            _currentLineThickness = value;
        };
    }

    private void SetupSettingsToggle()
    {
        SettingsToggleButton.Button.OnPressed += _ => ToggleSettingsVisibility();
        UpdateSettingsVisibility();
    }
}
