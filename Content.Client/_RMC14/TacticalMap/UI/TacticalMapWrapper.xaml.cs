    private void UpdateResponsiveTopButton(TacticalMapButton button)
    {
        if (!_responsiveTopButtonTexts.TryGetValue(button, out var fullText))
            return;

        var compact = ShouldCompactTopButtons();
        button.Text = compact
            ? GetCompactButtonText(fullText)
            : fullText;
        if (_responsiveTopButtonMinWidths.TryGetValue(button, out var minWidth))
            button.MinWidth = compact ? CompactTopButtonWidth : minWidth;
        button.ToolTip = fullText;
        button.Button.ToolTip = fullText;
    }

    private void SetButtonDisplayText(TacticalMapButton button, string text)
    {
        if (_responsiveTopButtonTexts.ContainsKey(button))
        {
            _responsiveTopButtonTexts[button] = text;
            UpdateResponsiveTopButton(button);
            return;
        }

        button.Text = text;
    }

    private bool ShouldCompactTopButtons()
    {
        return MainButtonRow.Width > 0f && MainButtonRow.Width <= CompactTopButtonThreshold;
    }

    private static string GetCompactButtonText(string text)
    {
        foreach (var c in text)
        {
            if (!char.IsWhiteSpace(c))
                return c.ToString();
        }

        return string.Empty;
    }

    private void DrawCrtOverlay(DrawingHandleScreen handle)
    {
        if (_focusModeEnabled && !_focusHovered)
            return;

        var size = new Vector2(PixelWidth, PixelHeight);
        if (size.X <= 1f || size.Y <= 1f)
            return;

        var rect = UIBox2.FromDimensions(Vector2.Zero, size);

        handle.UseShader(_crtShader);
        handle.DrawRect(rect, Color.White);
        handle.UseShader(null);
    }

    private bool IsInQueenEyeMode()
    {
        var entMan = IoCManager.Resolve<IEntityManager>();
        var player = _player.LocalEntity;

        if (player == null)
            return false;

        if (entMan.HasComponent<GhostComponent>(player.Value))
            return true;

        if (!entMan.TryGetComponent<QueenEyeActionComponent>(player.Value, out QueenEyeActionComponent? queenEyeComp))
            return false;

        return queenEyeComp.Eye != null;
    }

    private void InvalidatePlayerCache()
    {
        _cachedPlayerEntity = null;
        _cachedPlayerNet = null;
        _cachedUserComponent = null;
    }

    private bool TryGetCachedPlayerData(out NetEntity playerNetId, out TacticalMapUserComponent userComponent)
    {
        playerNetId = default;
        userComponent = default!;

        var currentPlayer = _player.LocalEntity;
        if (currentPlayer == null)
        {
            InvalidatePlayerCache();
            return false;
        }

        if (_cachedPlayerEntity != currentPlayer)
        {
            var entMan = IoCManager.Resolve<IEntityManager>();
            if (!entMan.TryGetComponent<TacticalMapUserComponent>(currentPlayer.Value, out TacticalMapUserComponent? newUserComp))
            {
                InvalidatePlayerCache();
                return false;
            }

            _cachedPlayerEntity = currentPlayer;
            _cachedPlayerNet = entMan.GetNetEntity(currentPlayer.Value);
            _cachedUserComponent = newUserComp;
        }

        if (_cachedPlayerNet == null || _cachedUserComponent == null)
            return false;

        playerNetId = _cachedPlayerNet.Value;
        userComponent = _cachedUserComponent;
        return true;
    }

    private bool TryFindPlayerBlip(out Vector2i playerIndices)
    {
        playerIndices = default;

        if (!TryGetCachedPlayerData(out var playerNet, out TacticalMapUserComponent userComp))
            return false;

        foreach ((NetEntity entity, TacticalMapBlip blip) in userComp.Blips)
        {
            if (entity == playerNet)
            {
                playerIndices = blip.Indices;
                return true;
            }
        }

        return false;
    }
