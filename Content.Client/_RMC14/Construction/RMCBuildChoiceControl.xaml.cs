using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._RMC14.Construction;

[GenerateTypedNameReferences]
public sealed partial class RMCBuildChoiceControl : BoxContainer
{
    public RMCBuildChoiceControl()
    {
        RobustXamlLoader.Load(this);
    }

    public void Set(string name, Texture? icon, string? costText = null, bool canAfford = true)
    {
        NameLabel.Text = name;
        Icon.Texture = icon;
        Icon.Visible = icon != null;
        CostLabel.Text = costText ?? string.Empty;
        CostLabel.Visible = !string.IsNullOrEmpty(costText);
        Button.Disabled = !canAfford;
    }
}
