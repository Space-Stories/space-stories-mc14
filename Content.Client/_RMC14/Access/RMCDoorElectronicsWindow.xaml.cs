using System.Numerics;
using Content.Client.UserInterface.Controls;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._RMC14.Access;

[GenerateTypedNameReferences]
public sealed partial class RMCDoorElectronicsWindow : FancyWindow
{
    private const float MinimumColumnWidth = 178;
    private const float ScrollbarSpace = 16;
    private static readonly Vector2 ViewportInset = new(16, 76);

    private Control? _windowRoot;

    public RMCDoorElectronicsWindow()
    {
        RobustXamlLoader.Load(this);

        AccessScroll.OnResized += UpdateColumns;
    }

    public void FitToViewport()
    {
        if (Parent is not { } root)
            return;

        _windowRoot = root;
        root.OnResized += UpdateViewportBounds;
        UpdateViewportBounds();
    }

    protected override void ExitedTree()
    {
        if (_windowRoot is { } root)
            root.OnResized -= UpdateViewportBounds;

        _windowRoot = null;
        base.ExitedTree();
    }

    public void FitAccessButtons()
    {
        foreach (var button in AccessLevels.ButtonsList.Values)
        {
            button.ClipText = true;
            button.ToolTip = button.Text;
            button.HorizontalExpand = true;
        }

        UpdateColumns();
    }

    private void UpdateViewportBounds()
    {
        if (_windowRoot is not { } root || root.Size.X <= 0 || root.Size.Y <= 0)
            return;

        MaxSize = Vector2.Max(MinSize, root.Size - ViewportInset);
        var maxPosition = Vector2.Max(Vector2.Zero, MaxSize - Vector2.Min(SetSize, MaxSize));
        LayoutContainer.SetPosition(this, Vector2.Clamp(Position, Vector2.Zero, maxPosition));
    }

    private void UpdateColumns()
    {
        var columns = Math.Clamp((int) ((AccessScroll.Size.X - ScrollbarSpace) / MinimumColumnWidth),
            1, Math.Max(1, AccessLevels.ChildCount));
        if (AccessLevels.Columns != columns)
            AccessLevels.Columns = columns;
    }
}
