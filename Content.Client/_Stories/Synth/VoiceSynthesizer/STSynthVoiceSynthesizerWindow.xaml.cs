using Content.Shared._Stories.Synth.VoiceSynthesizer;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Timing;

namespace Content.Client._Stories.Synth.VoiceSynthesizer;

[GenerateTypedNameReferences]
public sealed partial class STSynthVoiceSynthesizerWindow : DefaultWindow
{
    [Dependency] private readonly ILocalizationManager _loc = default!;

    public event Action<string>? OnLinePressed;

    private bool _onCooldown;

    private System.Threading.CancellationTokenSource? _cooldownCancel;

    private readonly List<(string Id, string Text, Button SearchButton)> _allLines = new();

    private readonly ButtonGroup _categoryGroup = new();

    private readonly List<(STSynthVoiceCategoryButton Button, ScrollContainer Content)> _categories = new();

    public STSynthVoiceSynthesizerWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        SearchBar.OnTextChanged += _ => UpdateSearch();
    }

    public void Populate(IPrototypeManager prototypes, IComponentFactory compFactory)
    {
        var byCategory = new Dictionary<string, (string Name, BoxContainer Content)>();

        foreach (var proto in prototypes.EnumeratePrototypes<EntityPrototype>())
        {
            if (!proto.TryGetComponent(out STSynthVoiceLineComponent? line, compFactory))
                continue;

            var categoryName = Loc.GetString(line.Category);
            if (!byCategory.TryGetValue(categoryName, out var tab))
            {
                var content = new BoxContainer
                {
                    Orientation = BoxContainer.LayoutOrientation.Vertical,
                    VerticalExpand = true,
                };

                var scroll = new ScrollContainer
                {
                    VerticalExpand = true,
                    HorizontalExpand = true,
                    HScrollEnabled = false,
                    Visible = _categories.Count == 0,
                };
                scroll.AddChild(content);
                CategoryContents.AddChild(scroll);

                var categoryButton = new STSynthVoiceCategoryButton
                {
                    Text = categoryName,
                    Group = _categoryGroup,
                    Pressed = _categories.Count == 0,
                };
                categoryButton.OnPressed += _ => SelectCategory(scroll);
                CategoryButtons.AddChild(categoryButton);
                _categories.Add((categoryButton, scroll));

                tab = (categoryName, content);
                byCategory[categoryName] = tab;
            }

            var lineText = Loc.GetString(line.Text);
            var labelId = $"{line.Text}-label";
            var labelText = _loc.HasString(labelId) ? _loc.GetString(labelId) : lineText;
            var lineId = proto.ID;

            var tabButton = new Button
            {
                Text = labelText,
                HorizontalExpand = true,
                ToolTip = lineText,
            };
            tabButton.OnPressed += _ => TryPlayLine(lineId);
            tab.Content.AddChild(tabButton);

            var searchButton = new Button
            {
                Text = labelText,
                HorizontalExpand = true,
                ToolTip = lineText,
                Visible = false,
            };
            searchButton.OnPressed += _ => TryPlayLine(lineId);
            SearchResultsContainer.AddChild(searchButton);

            _allLines.Add((lineId, $"{labelText}\n{lineText}", searchButton));
        }
    }

    public void SetTheme(bool useAlternateSound)
    {
        Title = Loc.GetString(useAlternateSound
            ? "st-hazmat-joe-voice-panel-title"
            : "st-working-joe-voice-panel-title");
    }

    private void SelectCategory(ScrollContainer selected)
    {
        foreach (var (_, content) in _categories)
        {
            content.Visible = content == selected;
        }
    }

    private void TryPlayLine(string lineId)
    {
        if (_onCooldown)
            return;

        OnLinePressed?.Invoke(lineId);
    }

    private void UpdateSearch()
    {
        var search = SearchBar.Text.Trim();

        if (string.IsNullOrEmpty(search))
        {
            CategoryView.Visible = true;
            SearchResultsScroll.Visible = false;
            return;
        }

        CategoryView.Visible = false;
        SearchResultsScroll.Visible = true;

        foreach (var (_, text, button) in _allLines)
        {
            button.Visible = text.Contains(search, StringComparison.CurrentCultureIgnoreCase);
        }
    }

    public void SetCooldown(bool onCooldown, TimeSpan remaining)
    {
        _onCooldown = onCooldown;

        _cooldownCancel?.Cancel();
        _cooldownCancel = null;

        if (onCooldown && remaining > TimeSpan.Zero)
        {
            _cooldownCancel = new System.Threading.CancellationTokenSource();
            Timer.Spawn(remaining, () => _onCooldown = false, _cooldownCancel.Token);
        }
    }

    public override void Close()
    {
        base.Close();
        _cooldownCancel?.Cancel();
        _cooldownCancel = null;
    }
}
