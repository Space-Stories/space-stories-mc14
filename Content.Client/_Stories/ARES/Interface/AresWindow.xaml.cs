using Content.Client.UserInterface.Controls;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Stories.ARES.Interface;

[GenerateTypedNameReferences]
public sealed partial class AresWindow : FancyWindow
{
    public AresWindow() => RobustXamlLoader.Load(this);

    public void SetMessageText(string text)
    {
        Message.Text = text;
        Message.Input.CursorPosition = new TextEdit.CursorPos(text.Length, TextEdit.LineBreakBias.Top);
    }
}
