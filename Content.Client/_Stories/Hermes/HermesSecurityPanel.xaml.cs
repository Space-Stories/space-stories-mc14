using Content.Client._RMC14.UserInterface.Crt;
using Content.Shared._Stories.ARES.Interface;
using Content.Shared._Stories.Hermes;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Stories.Hermes;

[GenerateTypedNameReferences]
public sealed partial class HermesSecurityPanel : BoxContainer
{
    public event Action<HermesActionMessage, string>? Action;

    public HermesSecurityPanel()
    {
        RobustXamlLoader.Load(this);
        Lockdown.OnPressed += _ => Action?.Invoke(new HermesActionMessage(HermesAction.Lockdown),
            Loc.GetString("stories-hermes-confirm-lockdown"));
        foreach (var iff in Enum.GetValues<HermesIff>())
            Iff.AddItem(Loc.GetString($"stories-hermes-iff-{iff}"), (int) iff);
        Iff.OnItemSelected += id => Action?.Invoke(new HermesActionMessage(HermesAction.ChangeIff, iff: (HermesIff) id),
            Loc.GetString("stories-hermes-confirm-iff", ("iff", Loc.GetString($"stories-hermes-iff-{(HermesIff) id}"))));
    }

    public void Refresh(AresSecurityView data, TimeSpan now, bool canChangeIff)
    {
        Vents.RemoveAllChildren();
        Lockdown.Text = Loc.GetString(data.LockedDown ? "stories-hermes-lift-lockdown" : "stories-hermes-start-lockdown");
        Lockdown.Disabled = data.DoorCount == 0 || now < data.LockdownReadyAt;
        LockdownStatus.Text = Loc.GetString(data.LockedDown ? "stories-hermes-lockdown-active" : "stories-hermes-lockdown-inactive");
        LockdownStatus.Tone = data.LockedDown ? RMCCrtTone.Warning : RMCCrtTone.Muted;
        SecurityStatus.Text = Loc.GetString("stories-hermes-security-status", ("doors", data.DoorCount),
            ("sentries", data.SentryCount), ("vents", data.Vents.Count));
        Iff.SelectId((int) data.Iff);
        Iff.Disabled = !canChangeIff || data.SentryCount == 0;
        foreach (var vent in data.Vents)
        {
            var row = new HermesVentRow();
            row.Location.Text = vent.Name;
            row.Status.Text = Loc.GetString(vent.Welded ? "stories-hermes-welded" :
                vent.Available ? "stories-hermes-ready" : "stories-hermes-recharging");
            row.Status.Tone = vent.Welded ? RMCCrtTone.Warning : vent.Available ? RMCCrtTone.Good : RMCCrtTone.Muted;
            row.Release.Disabled = !vent.Available;
            row.Release.OnPressed += _ => Action?.Invoke(new HermesActionMessage(HermesAction.ReleaseGas, target: vent.Entity),
                Loc.GetString("stories-hermes-confirm-gas", ("vent", vent.Name)));
            Vents.AddChild(row);
        }
    }
}
